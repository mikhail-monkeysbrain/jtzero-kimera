#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

export JTZERO_FLOW_RETURN_GUI=1

cat <<'EOF'
======================================================================
JT-ZERO — HAND MOVE / RETURN-TO-TARGET GUI
======================================================================
Моторы НЕ нужны.

Сценарий:
  1) аппарат неподвижно на стартовой точке;
  2) дождаться FLIGHT READY;
  3) GUI автоматически запомнит старт как TARGET;
  4) переместить аппарат руками к дальней точке;
  5) в дальней точке ПОЛНОСТЬЮ остановиться и нажать B;
  6) вернуть аппарат ФИЗИЧЕСКИ в исходную точку;
  7) в физической исходной точке остановиться и нажать H;
  8) GUI сразу выведет EKF closure, RAW closure proxy и dYaw.

GUI использует LOCAL_POSITION_NED EKF — то есть именно ту позицию,
которую сейчас считает ArduPilot.

Клавиши:
  SPACE  — сделать текущую позицию A/целью и обнулить forensic;
  B      — отметить дальнюю точку/разворот;
  H      — отметить ФИЗИЧЕСКОЕ возвращение в HOME;
  C      — очистить хвост траектории;
  Q/ESC  — завершить.

Ничего не ARM-ится и flight mode не меняется.
======================================================================
EOF

exec bash "$ROOT/tools/run_optical_flow_flight_current_mount.sh"
