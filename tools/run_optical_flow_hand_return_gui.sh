#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

export JTZERO_FLOW_RETURN_GUI=1

cat <<'EOF'
======================================================================
JT-ZERO — HAND MOVE / RETURN-TO-TARGET GUI
======================================================================
Моторы НЕ нужны.

Сценарий:
  1) аппарат неподвижно на стартовой точке;
  2) дождаться FLIGHT READY;
  3) GUI автоматически запомнит старт как TARGET;
  4) перемещать аппарат руками по столу/поверхности;
  5) вернуть оранжевую текущую точку в зелёный TARGET;
  6) при расстоянии <=25 мм появится TARGET REACHED.

GUI использует LOCAL_POSITION_NED EKF — то есть именно ту позицию,
которую сейчас считает ArduPilot.

Клавиши:
  SPACE  — сделать текущую позицию новой целью;
  C      — очистить хвост траектории;
  Q/ESC  — завершить.

Ничего не ARM-ится и flight mode не меняется.
======================================================================
EOF

exec bash "$ROOT/tools/run_optical_flow_flight_current_mount.sh"
