#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

export JTZERO_FLOW_RETURN_GUI=1
export JTZERO_FLOW_RETURN_MANUAL_TARGET=1

cat <<'EOF'
======================================================================
JT-ZERO — РУЧНОЙ ПЕРЕНОС / ВОЗВРАТ В ИСХОДНУЮ ТОЧКУ
======================================================================
Моторы НЕ нужны. Арминг не требуется.

Теперь GUI сам показывает текущий шаг крупной инструкцией.

ПРОТОКОЛ:
  1) Запусти тест и держи аппарат неподвижно до ГОТОВНОСТЬ СИСТЕМЫ.
  2) После ГОТОВНОСТЬ СИСТЕМЫ ПОДНИМИ аппарат руками на удобную высоту.
     Небольшие изменения roll/pitch/yaw допустимы.
  3) Удерживай аппарат неподвижно 2-3 секунды и нажми ПРОБЕЛ.
     Это физическая точка A/ДОМОЙ. Только после ПРОБЕЛ начинается измерение.
  4) Перенеси аппарат естественно примерно на 300-500 мм к точке B.
     Высота и ориентация могут немного меняться.
  5) В B полностью остановись, подожди 2-3 секунды и нажми B.
  6) Верни аппарат ФИЗИЧЕСКИ в ту же точку A.
     Не пытайся попасть в A по индикатору EKF на экране.
  7) В A полностью остановись, подожди 2-3 секунды и нажми H.
  8) После H ещё 2-3 секунды держи аппарат неподвижно, затем Q/ESC.

КЛАВИШИ:
  ПРОБЕЛ  — установить A/ДОМОЙ и обнулить диагностику
  B      — отметить дальнюю точку
  H      — подтвердить физический возврат в A
  C      — очистить только хвост EKF-траектории
  Q/ESC  — завершить

НА ЭКРАНЕ:
  оранжевая точка — EKF LOCAL_POSITION_NED
  голубая точка   — независимый RAW NED интеграл оптического потока
  RAW NED замыкание — главный диагностический loop-closure
  RAW BODY / LOS  — контрольные старые интегралы
  Крен/тангаж/курс — текущая ориентация FC
  TF-Luna         — текущая дистанция

ВАЖНО:
  - точка A больше НЕ ставится автоматически после ГОТОВНОСТЬ СИСТЕМЫ;
  - A ставится только ПРОБЕЛ после того, как ты удобно поднял аппарат;
  - моторы не запускаются и режим полёта не меняется.
======================================================================
EOF

exec bash "$ROOT/tools/run_optical_flow_flight_current_mount.sh"
