#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

export JTZERO_FLOW_RETURN_GUI=1
export JTZERO_FLOW_RETURN_MANUAL_TARGET=1
# В ArduPilot EKF3 до takeoff optical flow принудительно обнуляется при AGL <0.5 м.
# Для ручной bench-диагностики подаём синтетический range 0.60 м, а publisher
# масштабирует flow по реальному TF-Luna/camera height, сохраняя метрическую скорость.
export JTZERO_FLOW_BENCH_HEIGHT=0.60

cat <<'EOF'
======================================================================
JT-ZERO — РУЧНОЙ ПЕРЕНОС / ВОЗВРАТ В ИСХОДНУЮ ТОЧКУ
======================================================================
Моторы НЕ нужны. Арминг не требуется.

ВАЖНО: это теперь СПЕЦИАЛЬНЫЙ РУЧНОЙ ДИАГНОСТИЧЕСКИЙ РЕЖИМ.
ArduPilot до обнаружения takeoff и ниже 0.5 м принудительно обнуляет optical flow.
Поэтому в FC для этого теста подаётся синтетическая высота 0.60 м.
Реальный TF-Luna всё равно читается и используется для метрического масштаба flow.
Это НЕ полётная конфигурация.

GUI сам показывает текущий шаг крупной инструкцией.

ПРОТОКОЛ:
  1) Запусти тест и держи аппарат неподвижно до ГОТОВНОСТЬ СИСТЕМЫ.
  2) После ГОТОВНОСТЬ СИСТЕМЫ ПОДНИМИ аппарат руками на удобную высоту.
     Небольшие изменения roll/pitch/yaw допустимы.
  3) Удерживай аппарат неподвижно 2-3 секунды и нажми ПРОБЕЛ.
     Это физическая точка A/ДОМОЙ. Только после ПРОБЕЛ начинается измерение.
  4) Перенеси аппарат примерно на 200-400 мм к точке B.
     Во время переноса сделай небольшие естественные roll/pitch и небольшой yaw.
     Не делай резких рывков и не закрывай камеру рукой.
  5) В B полностью остановись, подожди 2-3 секунды и нажми B.
  6) Верни аппарат ФИЗИЧЕСКИ в ту же точку A.
     На обратном пути снова допустимы небольшие roll/pitch/yaw.
     Не пытайся попасть в A по индикатору EKF на экране.
  7) В A полностью остановись, подожди 3-5 секунд и нажми H.
  8) После H ещё 3-5 секунд держи аппарат неподвижно, затем Q/ESC.

КРИТЕРИЙ ЭТОГО ДИАГНОСТИЧЕСКОГО ПРОГОНА:
  RAW NED closure < 20 мм
  EKF closure     < 30 мм
  invalid flow    < 3%
  длинных серий invalid подряд быть не должно.

КЛАВИШИ:
  ПРОБЕЛ  — установить A/ДОМОЙ и обнулить диагностику
  B      — отметить дальнюю точку
  H      — подтвердить физический возврат в A
  C      — очистить только хвост EKF-траектории
  Q/ESC  — завершить

НА ЭКРАНЕ:
  оранжевая точка — EKF LOCAL_POSITION_NED
  голубая точка   — независимый RAW NED интеграл оптического потока
  RAW NED замыкание — главный диагностический loop-closure
  RAW BODY / LOS  — контрольные старые интегралы
  Крен/тангаж/курс — текущая ориентация FC
  TF-Luna         — текущая дистанция

ВАЖНО:
  - точка A больше НЕ ставится автоматически после ГОТОВНОСТЬ СИСТЕМЫ;
  - A ставится только ПРОБЕЛ после того, как ты удобно поднял аппарат;
  - моторы не запускаются и режим полёта не меняется;
  - синтетические 0.60 м используются ТОЛЬКО внутри этого ручного теста;
  - обычный flight launcher продолжает использовать настоящий TF-Luna.
======================================================================
EOF

exec bash "$ROOT/tools/run_optical_flow_flight_current_mount.sh"
