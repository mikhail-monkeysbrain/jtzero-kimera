#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

export JTZERO_FLOW_RETURN_GUI=0
export JTZERO_FLOW_ROTATION_GUI=1

cat <<'EOF'
======================================================================
JT-ZERO — ДИАГНОСТИКА ВРАЩЕНИЯ
======================================================================
Моторы не нужны. Арминг скрипт не выполняет.

ЦЕЛЬ:
  отдельно проверить реакцию OpticalFlow/EKF на roll/pitch/yaw,
  не смешивая её с A→B→A.

ПРОТОКОЛ:
  1) Поставьте аппарат устойчиво и запустите тест.
  2) Дождитесь надписи «СИСТЕМА ГОТОВА».
  3) Коротко наклоните аппарат по КРЕНУ примерно на ±5° и верните.
  4) Подождите 2–3 секунды.
  5) Коротко наклоните по ТАНГАЖУ примерно на ±5° и верните.
  6) Если удобно — небольшой КУРС ±10° и обратно.
  7) Не переносите аппарат по XY специально.
  8) После возврата в исходную ориентацию подождите 5 секунд.
  9) Нажмите Q или ESC.

GUI показывает:
  - крен / тангаж / курс;
  - gyro X/Y;
  - optical flow X/Y;
  - остаток FLOW-GYRO;
  - эквивалентную ложную скорость;
  - EKF |Vxy|;
  - TF-Luna и задержку кадра;
  - живое видео OV9281.

Все инструкции интерфейса — на русском.
======================================================================
EOF

exec bash "$ROOT/tools/run_optical_flow_flight_current_mount.sh"
