#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

export JTZERO_FLOW_RETURN_GUI=1
export JTZERO_FLOW_RETURN_MANUAL_TARGET=1
export JTZERO_FLOW_BENCH_HEIGHT=0.60

cat <<'EOF'
======================================================================
JT-ZERO — СТРЕСС-ТЕСТ FRONTEND OPTICAL FLOW
======================================================================
Моторы НЕ нужны. Арминг не требуется.
Маршрут воспроизводить НЕ НУЖНО.

ЦЕЛЬ:
  измерить устойчивость frontend по фактической сложности каждого кадра,
  а не сравнивать прямой и обратный ручной маршрут.

ПРОТОКОЛ:
  1) Дождись «СИСТЕМА ГОТОВА».
  2) Нажми ПРОБЕЛ — это только начало анализируемого участка.
  3) 5-10 секунд двигай аппарат спокойно.
  4) 10-20 секунд двигай естественно: перенос, изменение высоты,
     небольшие roll/pitch/yaw.
  5) Сделай несколько более быстрых, но безопасных переносов/наклонов.
  6) Остановись на 3-5 секунд.
  7) Нажми Q/ESC.

B и H НЕ НУЖНЫ.
Не пытайся повторять какую-либо траекторию.

После теста:
  LATEST="$(ls -td /home/vio/jtzero_runs/*_OPTICAL_FLOW_FLIGHT | head -1)"
  python3 tools/analyze_optical_flow_frontend_stress.py "$LATEST/optical_flow_mavlink.csv"

ВАЖНО:
  synthetic 0.60 м используется только для ручной bench-диагностики.
  Реальный TF-Luna продолжает использоваться для метрического масштаба.
======================================================================
EOF

exec bash "$ROOT/tools/run_optical_flow_flight_current_mount.sh"
